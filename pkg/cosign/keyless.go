// For attestations we need a DSSE entry so that the verification code can
// extract the signature from the bundle (intoto_v002 is not yet generated by
// the upstream helper). Use the DSSE envelope uploader.
var tlogUploadDSSE = cosign.TLogUploadDSSEEnvelope

