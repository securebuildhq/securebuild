// This code path is invoked **only** by the VM-based build pipeline via
// pkg/listener/update-build-image-status.go.  The legacy local-builder path
// continues to use the key-based helpers in cosign-api.go.
//
// Failures in Fulcio or Rekor are surfaced as errors to the caller but do not
// abort the overall image build; the listener logs a warning and continues so
// that a transient Sigstore outage does not break the build pipeline.

