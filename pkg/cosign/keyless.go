// Fulcio
type fulcioSigningClient interface {
	SigningCert(fulcioclient.CertificateRequest, string) (*fulcioclient.CertificateResponse, error)
}

var (
	fulcioClientOnce   sync.Once
	sharedFulcioClient fulcioSigningClient
	// newFulcioClient lazily initialises and returns a singleton Fulcio client
	newFulcioClient = func(u *url.URL) fulcioSigningClient {
		fulcioClientOnce.Do(func() {
			sharedFulcioClient = fulcioclient.NewClient(u)
		})
		return sharedFulcioClient
	}
)

// Rekor
var (
	rekorClientMu      sync.Mutex
	cachedRekorClients = make(map[string]*generatedclient.Rekor)
	// getRekorClient returns a cached Rekor client per base URL, creating it
	// on first use. This avoids leaking sockets by reusing the underlying
	// http.Client across invocations.
	getRekorClient = func(baseURL string) (*generatedclient.Rekor, error) {
		rekorClientMu.Lock()
		defer rekorClientMu.Unlock()
		if c, ok := cachedRekorClients[baseURL]; ok {
			return c, nil
		}
		c, err := rekorclient.GetRekorClient(baseURL)
		if err != nil {
			return nil, err
		}
		cachedRekorClients[baseURL] = c
		return c, nil
	}
)

